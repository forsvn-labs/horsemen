"""Check the canvas design fixture. This is a design check, not product code.

python3 docs/show-me/canvas-workspace/check.py            # canonical form, references, limits, mock data
python3 docs/show-me/canvas-workspace/check.py --schema   # also run a JSON Schema validator (needs uvx)
python3 docs/show-me/canvas-workspace/check.py --write    # rewrite the fixture in canonical form and rebuild fixture.js

The rules come from docs/product/canvas-workspace.md. The fixture is fictional.
"""
import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE / 'fixture'
SCHEMA = HERE.parent.parent / 'product' / 'canvas.schema.json'
NODE_FIRST = ('id', 'type', 'x', 'y', 'width', 'height')
EDGE_FIRST = ('id', 'fromNode', 'toNode')
MEDIA_TYPES = ('.png', '.jpg', '.jpeg', '.gif', '.webp', '.svg', '.csv', '.tsv', '.xlsx')
MAX_MEDIA = 1024 * 1024
MAX_CANVAS = 512 * 1024


def dumps(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'), sort_keys=True)


def line(item, first):
    keys = [k for k in first if k in item] + sorted(k for k in item if k not in first)
    return '{' + ','.join(dumps(k) + ':' + dumps(item[k]) for k in keys) + '}'


def block(name, items, first):
    if not items:
        return dumps(name) + ':[]'
    return dumps(name) + ':[\n' + ',\n'.join(line(item, first) for item in items) + '\n]'


def canonical(doc):
    """One element on each line. Groups first, then nodes by id; edges by id."""
    nodes = sorted(doc.get('nodes', []), key=lambda n: (n.get('type') != 'group', n['id']))
    edges = sorted(doc.get('edges', []), key=lambda e: e['id'])
    parts = ['"horsemen":' + dumps(doc.get('horsemen', {'version': 1})),
             block('nodes', nodes, NODE_FIRST), block('edges', edges, EDGE_FIRST)]
    parts += [dumps(k) + ':' + dumps(doc[k]) for k in sorted(doc) if k not in ('horsemen', 'nodes', 'edges')]
    return '{\n' + ',\n'.join(parts) + '\n}\n'


def headings(markdown):
    """Heading text by level, outside fenced code."""
    found, fenced = [], False
    for row in markdown.splitlines():
        if re.match(r'\s*(```|~~~)', row):
            fenced = not fenced
        match = None if fenced else re.match(r'(#{1,6})\s+(.*?)\s*#*\s*$', row)
        if match:
            found.append((len(match.group(1)), match.group(2).strip().lower()))
    return found


def has_heading(markdown, subpath):
    """`#Heading` matches a heading with that text. `#Parent#Child` needs Child below Parent."""
    want = [part.strip().lower() for part in subpath.split('#')[1:]]
    found, at, level = headings(markdown), 0, 0
    for name in want:
        for i in range(at, len(found)):
            if level and found[i][0] <= level:
                return False
            if found[i][1] == name:
                at, level = i + 1, found[i][0]
                break
        else:
            return False
    return bool(want)


def semantic(doc, root):
    """Rules that a JSON Schema cannot state."""
    errors, ids = [], set()
    nodes, edges = doc.get('nodes', []), doc.get('edges', [])
    for item in nodes + edges:
        if item['id'] in ids:
            errors.append(f"duplicate id {item['id']}")
        ids.add(item['id'])
    node_ids = {node['id'] for node in nodes}
    for edge in edges:
        for end in ('fromNode', 'toNode'):
            if edge[end] not in node_ids:
                errors.append(f"edge {edge['id']} names a missing node {edge[end]}")
    for node in nodes:
        if node.get('type') != 'file':
            continue
        target = root / node['file']
        if not target.is_file() or root not in target.resolve().parents:
            errors.append(f"node {node['id']} names a missing file {node['file']}")
            continue
        if node['file'].startswith('.horsemen/media/'):
            if target.suffix.lower() not in MEDIA_TYPES:
                errors.append(f"node {node['id']} names an unsupported media type")
            if target.stat().st_size > MAX_MEDIA:
                errors.append(f"node {node['id']} names a file larger than 1 MiB")
        if 'subpath' in node and target.suffix.lower() == '.md' and not has_heading(target.read_text(encoding='utf-8'), node['subpath']):
            errors.append(f"node {node['id']} names a missing heading {node['subpath']}")
    return errors


def fixture_js():
    """The mock reads the same files that this script checks."""
    data = {
        'canvases': {p.stem: json.loads(p.read_text(encoding='utf-8')) for p in sorted((ROOT / '.horsemen/canvas').glob('*.canvas'))},
        'files': {str(p.relative_to(ROOT)): p.read_text(encoding='utf-8')
                  for p in sorted(ROOT.rglob('*')) if p.is_file() and p.suffix in ('.md', '.csv', '.svg')},
    }
    return '/* Generated by check.py --write from fixture/. Fictional data. Do not edit. */\nwindow.FIXTURE=' + dumps(data) + ';\n'


def run_schema(valid, invalid):
    tool = shutil.which('check-jsonschema')
    command = [tool] if tool else ['uvx', 'check-jsonschema']
    if not tool and not shutil.which('uvx'):
        return ['--schema needs check-jsonschema or uvx on PATH']
    failures = []
    ok = subprocess.run([*command, '--schemafile', str(SCHEMA), *map(str, valid)], capture_output=True, text=True)
    if ok.returncode:
        failures.append('schema rejected a valid fixture:\n' + ok.stdout + ok.stderr)
    for path in invalid:
        bad = subprocess.run([*command, '--schemafile', str(SCHEMA), str(path)], capture_output=True, text=True)
        expected_fail = path.name.startswith('schema-')
        if expected_fail and bad.returncode == 0:
            failures.append(f'schema accepted {path.name}')
        if not expected_fail and bad.returncode:
            failures.append(f'schema rejected {path.name}, which must fail only the reference rules:\n' + bad.stdout)
    return failures


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--schema', action='store_true')
    args = parser.parse_args()
    valid = sorted((ROOT / '.horsemen/canvas').glob('*.canvas'))
    invalid = sorted((ROOT / 'invalid').glob('*.json'))
    failures = []
    if not valid or not invalid:
        failures.append('fixture files are missing')
    for path in valid:
        text = path.read_text(encoding='utf-8')
        doc = json.loads(text)
        if args.write and canonical(doc) != text:
            path.write_text(canonical(doc), encoding='utf-8')
            text = canonical(doc)
        if canonical(doc) != text:
            failures.append(f'{path.name} is not in canonical form; run with --write')
        if canonical(json.loads(canonical(doc))) != canonical(doc):
            failures.append(f'{path.name} changes when it is written again')
        if len(text.encode()) > MAX_CANVAS:
            failures.append(f'{path.name} is larger than 512 KiB')
        elements = len(doc.get('nodes', [])) + len(doc.get('edges', []))
        if sum(row.startswith('{"id":') for row in text.splitlines()) != elements:
            failures.append(f'{path.name} does not keep one element on each line')
        failures += [f'{path.name}: {error}' for error in semantic(doc, ROOT)]
    for path in invalid:
        if path.name.startswith('semantic-') and not semantic(json.loads(path.read_text(encoding='utf-8')), ROOT):
            failures.append(f'{path.name} passed the reference rules')
    built = HERE / 'fixture.js'
    if args.write:
        built.write_text(fixture_js(), encoding='utf-8')
    if not built.is_file() or built.read_text(encoding='utf-8') != fixture_js():
        failures.append('fixture.js is stale; run with --write')
    if args.schema:
        failures += run_schema(valid, invalid)
    if failures:
        print('FAIL\n' + '\n'.join('- ' + f for f in failures))
        return 1
    checks = 'canonical form, references, limits, mock data' + (', JSON Schema' if args.schema else '')
    print(f'PASS: {len(valid)} canvases, {len(invalid)} invalid cases ({checks})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
