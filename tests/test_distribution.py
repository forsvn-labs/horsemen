"""Distribution failures: missing resources, drift, leaked files, and overwrites."""
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest
import zipfile

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("distribution", ROOT / "scripts/distribution.py")
distribution = importlib.util.module_from_spec(spec)
spec.loader.exec_module(distribution)


class Distribution(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.source = self.root / "source"
        shutil.copytree(ROOT / "horsemen", self.source / "horsemen")
        shutil.copy2(ROOT / "LICENSE", self.source / "LICENSE")
        self.output = self.root / "artifacts"

    def test_project_paths_work_in_a_renamed_checkout(self):
        source = self.root / "renamed-checkout"
        shutil.copytree(ROOT, source, ignore=shutil.ignore_patterns(".git", ".venv", "__pycache__"))
        result = subprocess.run(
            [sys.executable, "-B", str(source / "horsemen/scripts/horsemen.py"),
             "check", str(source), "--json"], capture_output=True, text=True,
        )
        report = json.loads(result.stdout)
        self.assertEqual(report["errors"], [])
        self.assertEqual(result.returncode, 0)

    def test_archive_is_complete_and_reproducible(self):
        archive = distribution.build_skill(self.source, self.output)
        other = distribution.build_skill(self.source, self.root / "other")
        self.assertEqual(archive.read_bytes(), other.read_bytes())
        with zipfile.ZipFile(archive) as package:
            for path in (self.source / "horsemen").rglob("*"):
                if path.is_file() and "__pycache__" not in path.parts:
                    self.assertEqual(package.read(str(path.relative_to(self.source))), path.read_bytes())
            self.assertIn("horsemen/scripts/horsemen_core/legacy.py", package.namelist())
            self.assertIn("horsemen/references/templates.md", package.namelist())
            for name in ("scripts/horsemen_core/canvas.py", "scripts/horsemen_core/agent_tools.py",
                         "scripts/horsemen_core/mcp.py", "scripts/test_canvas_cli.py", "references/canvas.md"):
                self.assertIn("horsemen/" + name, package.namelist())
            self.assertEqual(package.read("horsemen/LICENSE"), (ROOT / "LICENSE").read_bytes())
        receipt = json.loads((self.output / "skill-manifest.json").read_text())
        self.assertEqual(receipt["version"], distribution.version(self.source))
        self.assertEqual(receipt["sha256"], hashlib.sha256(archive.read_bytes()).hexdigest())

    def test_packaged_skill_routes_writes_to_a_self_contained_editing_pass(self):
        archive = distribution.build_skill(self.source, self.output)
        with zipfile.ZipFile(archive) as package:
            entry = package.read("horsemen/SKILL.md").decode()
            guidance = package.read("horsemen/references/sync.md").decode()
            templates = package.read("horsemen/references/templates.md").decode()
        self.assertIn("## Before every prose write", entry)
        self.assertIn("references/sync.md#pre-save-edit", entry)
        self.assertIn("no-ai-slop", entry)
        self.assertIn("## Pre-save edit", guidance)
        self.assertIn("If the skill is unavailable", guidance)
        self.assertIn("changed prose", guidance)
        self.assertIn("sync.md#pre-save-edit", templates)

    def test_symlinks_fail_before_output(self):
        target = self.source / "horsemen/private.md"
        target.symlink_to(ROOT / "README.md")
        with self.assertRaises(ValueError):
            distribution.build_skill(self.source, self.output)
        self.assertFalse(self.output.exists())

    def test_unknown_files_fail_before_output(self):
        (self.source / "horsemen/.env").write_text("FAKE_SECRET=fixture")
        with self.assertRaises(ValueError):
            distribution.build_skill(self.source, self.output)
        self.assertFalse(self.output.exists())

    def test_local_install_metadata_is_not_distributed(self):
        metadata = self.source / "horsemen/scripts/horsemen.egg-info"
        metadata.mkdir()
        (metadata / "PKG-INFO").write_text("Generated by a local pip install")
        archive = distribution.build_skill(self.source, self.output)
        with zipfile.ZipFile(archive) as package:
            self.assertFalse(any(".egg-info" in name for name in package.namelist()))

    def test_missing_hook_dependency_fails_before_output(self):
        (self.source / "horsemen/scripts/horsemen_core/legacy.py").unlink()
        with self.assertRaises(ValueError):
            distribution.build_skill(self.source, self.output)
        self.assertFalse(self.output.exists())

    def test_missing_canvas_module_fails_before_output(self):
        for name in ("canvas.py", "agent_tools.py", "mcp.py"):
            source = self.root / ("source-" + name)
            shutil.copytree(self.source, source)
            (source / "horsemen/scripts/horsemen_core" / name).unlink()
            with self.assertRaises(ValueError):
                distribution.build_skill(source, self.root / ("out-" + name))
            self.assertFalse((self.root / ("out-" + name)).exists())

    def test_packaged_skill_explains_canvases(self):
        archive = distribution.build_skill(self.source, self.output)
        with zipfile.ZipFile(archive) as package:
            entry = package.read("horsemen/SKILL.md").decode()
            guide = package.read("horsemen/references/canvas.md").decode()
        self.assertIn("## Canvases", entry)
        self.assertIn("references/canvas.md", entry)
        for words in ("canvas_edit", "horsemen.py show", "horsemen.py canvas apply", "horsemen.py mcp install", ".horsemen/canvas/"):
            self.assertIn(words, guide)

    def test_packaged_skill_serves_the_tools_without_the_wheel(self):
        archive = distribution.build_skill(self.source, self.output)
        unpacked = self.root / "unpacked"
        with zipfile.ZipFile(archive) as package:
            package.extractall(unpacked)
        project = self.root / "project"
        shutil.copytree(ROOT / "tests/fixtures/canvas/workspace", project)
        requests = [{"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-06-18", "capabilities": {}}},
                    {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
                    {"jsonrpc": "2.0", "id": 3, "method": "tools/call", "params": {"name": "read", "arguments": {"target": "progress.canvas"}}}]
        result = subprocess.run([sys.executable, "-B", str(unpacked / "horsemen/scripts/horsemen.py"), "mcp"], cwd=project,
                                input="".join(json.dumps(r) + "\n" for r in requests), capture_output=True, text=True, timeout=60)
        self.assertEqual(result.returncode, 0, result.stderr)
        replies = [json.loads(line) for line in result.stdout.splitlines()]
        self.assertEqual([tool["name"] for tool in replies[1]["result"]["tools"]], ["read", "canvas_edit"])
        self.assertIn("11 nodes 7 edges", replies[2]["result"]["content"][0]["text"])
        check = subprocess.run([sys.executable, "-B", str(unpacked / "horsemen/scripts/horsemen_core/legacy.py"), "check", str(project), "--json"],
                               capture_output=True, text=True, timeout=60)
        self.assertFalse(any(item["code"].startswith("canvas") for item in json.loads(check.stdout)["errors"]), check.stdout)

    def test_existing_output_is_preserved(self):
        archive = distribution.build_skill(self.source, self.output)
        before = archive.read_bytes()
        with self.assertRaises(FileExistsError):
            distribution.build_skill(self.source, self.output)
        self.assertEqual(before, archive.read_bytes())

    def test_skill_license_cannot_drift(self):
        (self.source / "horsemen/LICENSE").write_text("Different terms")
        with self.assertRaises(ValueError):
            distribution.build_skill(self.source, self.output)
        self.assertFalse(self.output.exists())

    def test_executable_mode_is_preserved(self):
        script = self.source / "horsemen/scripts/horsemen.py"
        script.chmod(0o755)
        archive = distribution.build_skill(self.source, self.output)
        with zipfile.ZipFile(archive) as package:
            mode = package.getinfo("horsemen/scripts/horsemen.py").external_attr >> 16
            self.assertEqual(mode & 0o777, 0o755)

    def test_output_cannot_be_inside_source(self):
        with self.assertRaises(ValueError):
            distribution.build_skill(self.source, self.source / "horsemen/dist")


if __name__ == "__main__":
    unittest.main()
